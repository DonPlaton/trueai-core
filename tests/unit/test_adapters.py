def test_a_certificate_view_restates_what_a_certificate_never_asserts() -> None:
    pytest.importorskip("cryptography", reason="Signing needs the attestation extra")

    from trueai.core.certificates import issue_certificate
    from trueai.core.models import ScanOptions

    certificate = issue_certificate(report(findings=()), ScanOptions(), issued_at=NOW)

    view = certificate_view(certificate)

    assert "does not certify human authorship" in view.attests_only
    assert "does not certify that AI was never used" in view.attests_only


def test_every_check_is_shown_separately_rather_than_as_one_tick() -> None:
    """Four unknowns must not hide behind a single green answer."""

    pytest.importorskip("cryptography", reason="Signing needs the attestation extra")

    from trueai.core.certificates import CertificateVerification, issue_certificate
    from trueai.core.models import ScanOptions

    certificate = issue_certificate(report(findings=()), ScanOptions(), issued_at=NOW)
    verification = CertificateVerification(
        valid=False,
        certificate_id_valid=True,
        signature_present=False,
        signature_verified=None,
        artifact_verified=True,
        explanations=("the certificate is unsigned",),
    )

    view = certificate_view(certificate, verification)

    assert view.checks["identity_matches_contents"] is True
    assert view.checks["signature_present"] is False
    assert view.checks["signature_verified"] is None
    assert not view.valid


