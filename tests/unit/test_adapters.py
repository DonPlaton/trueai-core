def test_a_preview_separates_what_will_change_from_what_will_not() -> None:
    plan = RemediationPlan(
        policy="client-delivery",
        remediations=(
            Remediation(
                id="rem-1",
                remediation_id="strip.metadata",
                artifact_path="notes.md",
                finding_ids=("finding-000000000001",),
                description="Remove generator metadata.",
                safety=RemediationSafety.SAFE_METADATA,
            ),
        ),
        review_findings=("finding-000000000002",),
        preserved_findings=("finding-000000000003",),
        blocked_findings=("finding-000000000004",),
    )

    preview = remediation_preview(plan)

    assert not preview.changes_visible_content
    assert preview.needs_review == ("finding-000000000002",)
    assert preview.preserved == ("finding-000000000003",)
    assert preview.blocked == ("finding-000000000004",)


def test_a_destructive_step_is_marked_as_needing_explicit_consent() -> None:
    plan = RemediationPlan(
        policy="deep-clean",
        remediations=(
            Remediation(
                id="rem-1",
                remediation_id="rewrite.history",
                artifact_path="repo",
                finding_ids=(),
                description="Rewrite commit history.",
                safety=RemediationSafety.DESTRUCTIVE,
            ),
        ),
    )

    step = remediation_preview(plan).steps[0]

    assert step.requires_explicit_opt_in
    assert step.changes_visible_content


def test_an_unverifiable_integrity_result_is_unknown_not_false() -> None:
    """A check that did not run is not a check that failed."""

    evidence = integrity_evidence(
        IntegrityReport(status=IntegrityStatus.NOT_VERIFIABLE, explanation="No logical digest.")
    )

    assert evidence.visible_content_unchanged is None
    assert not evidence.verified


def test_matching_logical_digests_prove_the_visible_content_survived() -> None:
    evidence = integrity_evidence(
        IntegrityReport(
            status=IntegrityStatus.PASS,
            explanation="Metadata only.",
            logical_before_sha256="a" * 64,
            logical_after_sha256="a" * 64,
        )
    )

    assert evidence.visible_content_unchanged is True
    assert evidence.verified


def test_differing_logical_digests_report_a_visible_change() -> None:
    evidence = integrity_evidence(
        IntegrityReport(
            status=IntegrityStatus.FAIL,
            explanation="Content changed.",
            logical_before_sha256="a" * 64,
            logical_after_sha256="b" * 64,
        )
    )

    assert evidence.visible_content_unchanged is False


